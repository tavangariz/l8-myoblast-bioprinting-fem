#!/usr/bin/env python3
"""Fig. 2: cartridge and nozzle geometry, after Ning et al. (2018), Fig. 1.

(A) The axisymmetric domain with its dimensions, radial axis exaggerated. (B) The contraction at
true aspect ratio, with the mesh generated by Gmsh. Both panels are drawn from l8_geometry.py,
whose dimensions are those of the solver (L8_GEOM=ning). The element count depends on the Gmsh
version; Gmsh 4.15.2 gives the committed figure.

    python scripts/fig2_geometry.py
"""
from __future__ import annotations
import sys, pathlib
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import Polygon as MplPolygon, Arc

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import l8_style as S

# This figure is the geometry, so it is the last place that should hold a second copy of it.
from l8_geometry import GEOM, profile_points   # noqa: E402

Rin, Rmid = GEOM["Rin"], GEOM["Rmid"]
R_TIP = GEOM["Rtip"]                # Ø200 µm reference tip
z1, z2, z3 = GEOM["z1"], GEOM["z2"], GEOM["z3"]
Lc2, Lc1, Ltip = z1, z2, z3 - z2    # the dimensions Ning's Fig. 1 labels
L_STRAIGHT, L_CONE = z1, z2 - z1
MESH_M = 12

# Profile_points() returns (z, r) along the bore; this panel is drawn with r across and z
# down, and closes the section on the symmetry axis at each end.
_z, _r = profile_points()
PTS = [(0, 0)] + [(float(rr), float(zz)) for zz, rr in zip(_z, _r)] + [(0, z3)]


def build_mesh():
    """Generate the real mesh with the solver's own refinement fields."""
    import gmsh
    gmsh.initialize()
    gmsh.option.setNumber("General.Verbosity", 0)
    gmsh.model.add("fig1")
    gp = [gmsh.model.geo.addPoint(*c, 0) for c in PTS]
    gln = [gmsh.model.geo.addLine(gp[i], gp[i + 1]) for i in range(6)]
    gln.append(gmsh.model.geo.addLine(gp[6], gp[0]))
    gmsh.model.geo.addPlaneSurface([gmsh.model.geo.addCurveLoop(gln)])
    gmsh.model.geo.synchronize()
    f = gmsh.model.mesh.field
    td = f.add("Distance"); f.setNumbers(td, "CurvesList", [gln[4]]); f.setNumber(td, "Sampling", 200)
    tt = f.add("Threshold"); f.setNumber(tt, "InField", td)
    f.setNumber(tt, "SizeMin", R_TIP / MESH_M); f.setNumber(tt, "SizeMax", 2e-4)
    f.setNumber(tt, "DistMin", R_TIP); f.setNumber(tt, "DistMax", 5 * R_TIP)
    cd = f.add("Distance"); f.setNumbers(cd, "CurvesList", [gln[2], gln[3]]); f.setNumber(cd, "Sampling", 100)
    ct = f.add("Threshold"); f.setNumber(ct, "InField", cd)
    f.setNumber(ct, "SizeMin", 2 * R_TIP / MESH_M); f.setNumber(ct, "SizeMax", 2e-4)
    f.setNumber(ct, "DistMin", 2e-4); f.setNumber(ct, "DistMax", 8e-4)
    mn = f.add("Min"); f.setNumbers(mn, "FieldsList", [tt, ct]); f.setAsBackgroundMesh(mn)
    gmsh.model.mesh.generate(2)
    _, nc, _ = gmsh.model.mesh.getNodes()
    nodes = np.array(nc).reshape(-1, 3)[:, :2]
    tags, _ = gmsh.model.mesh.getElementsByType(2)
    _, econn = gmsh.model.mesh.getElementsByType(2)
    tri = np.array(econn).reshape(-1, 3) - 1
    gmsh.finalize()
    return nodes, tri, len(tri)


nodes, tri, n_elem = build_mesh()
P = S.PAPER
plt.rcParams.update(S.rc(P) if hasattr(S, "rc") else {})

MM = 1e3
# Two panels.
fig = plt.figure(figsize=(6.9044, 3.8167))
# Width set so the two panels are the same height.
gs = fig.add_gridspec(1, 2, width_ratios=[1.00, 1.13],
                      wspace=0.30, left=0.085, right=0.985,
                      top=0.905, bottom=0.145)
axA = fig.add_subplot(gs[0, 0])
axB = fig.add_subplot(gs[0, 1])

# Dimension lines, witness lines, arrowheads and the symmetry axis stay grey on purpose: l8_style's
# standing rule is that annotation never encodes anything, and on an engineering drawing the
# dimensions are annotation.
def _tint(hex_colour: str, weight: float) -> str:
    """`weight` of `hex_colour` over white. A wash of a palette entry, not a new colour."""
    r_, g_, b_ = (int(hex_colour[i:i + 2], 16) for i in (1, 3, 5))
    return "#%02X%02X%02X" % tuple(
        round(weight * c + (1 - weight) * 255) for c in (r_, g_, b_))


# No diameter colours.
WALL = S.INK                            # the boundary of the fluid, both panels
FILL = S.PANEL                          # the fluid itself, a pale neutral
# Mesh edges in s.mesh_c, one hue.
MESH = S.MESH_C                         # element edges, one measured hue, under the wall
MESH_LW = 0.3                           # pt; the wall is 1.2 pt
r = np.array([p_[0] for p_ in PTS]) * MM
z = np.array([p_[1] for p_ in PTS]) * MM
AN = P["annot"]

# This panel is a schematic, not a plot:
axA.add_patch(MplPolygon(np.column_stack([np.r_[r, -r[::-1]], np.r_[z, z[::-1]]]),
                         closed=True, facecolor=FILL, edgecolor=WALL, lw=1.4, zorder=3))
axA.plot([0, 0], [-1.2, z3 * MM + 1.2], color=S.MUTE, lw=0.7,
         ls=(0, (7, 3, 1.5, 3)), zorder=4)

EXT = dict(color=S.MUTE, lw=0.55, zorder=2)          # extension (witness) lines
ARR = dict(arrowstyle="<|-|>", color=S.INK, lw=0.8, shrinkA=0, shrinkB=0,
           mutation_scale=7)

def dim_v(x, za, zb, lab, from_r):
    """Vertical dimension at r = x, spanning za..zb, witness lines from the profile."""
    for zz, rr in zip((za, zb), from_r):
        axA.plot([x - 0.30, rr], [zz, zz], **EXT)
    axA.annotate("", xy=(x, za), xytext=(x, zb), arrowprops=ARR, zorder=5)
    axA.text(x - 0.34, (za + zb) / 2, lab, fontsize=AN, color=S.INK,
             ha="center", va="center", rotation=90, zorder=6,
             bbox=dict(fc="white", ec="none", pad=1.0))

def dim_h(zz, ra, rb, lab, from_z, va="bottom", dz=0.0):
    """Horizontal dimension at z = zz, spanning ra..rb, witness lines from the profile."""
    for rr, zsrc in zip((ra, rb), from_z):
        axA.plot([rr, rr], [zz, zsrc], **EXT)
    axA.annotate("", xy=(ra, zz), xytext=(rb, zz), arrowprops=ARR, zorder=5)
    axA.text(0, zz + dz, lab, fontsize=AN, color=S.INK, ha="center", va=va, zorder=6,
             bbox=dict(fc="white", ec="none", pad=1.0))

# Axial chain, on the left, innermost dimension nearest the part
dim_v(-3.45, 0, z1 * MM, "$L_{c2}$ = 10.5 mm", (-Rin * MM, -Rin * MM))
dim_v(-5.55, 0, z2 * MM, "$L_{c1}$ = 12.0 mm", (-Rin * MM, -Rmid * MM))
dim_v(-3.45, z2 * MM, z3 * MM, "$L$ = 10.0 mm", (-Rmid * MM, -R_TIP * MM))

# Diameters
dim_h(-2.15, -Rin * MM, Rin * MM, "$D_1$ = 4.2 mm", (0.0, 0.0), va="bottom", dz=-0.30)
dim_h(z2 * MM + 1.65, -Rmid * MM, Rmid * MM, "$D_2$ = 2.0 mm",
      (z2 * MM, z2 * MM), va="top", dz=0.30)

# The tip bore is far too small to dimension in place under radial exaggeration, so it is leadered
# out.
axA.annotate("$D$ = 100 / 200 /\n250 / 330 µm",
             xy=(R_TIP * MM, (z2 + z3) / 2 * MM),
             xytext=(0.95, (z2 + z3) / 2 * MM),
             fontsize=AN, color=S.INK, ha="left", va="center", zorder=6, linespacing=1.45,
             arrowprops=dict(arrowstyle="-", color=S.MUTE, lw=0.6))

# The drawing may not state a dimension the solver does not have.
for _lab, _val in (("$L_{c2}$ = 10.5 mm", Lc2), ("$L_{c1}$ = 12.0 mm", Lc1),
                   ("$L$ = 10.0 mm", Ltip), ("$D_1$ = 4.2 mm", 2 * Rin),
                   ("$D_2$ = 2.0 mm", 2 * Rmid)):
    _num = float(_lab.split("=")[1].strip().split()[0])
    assert abs(_num - _val * MM) < 1e-9, f"drawn {_lab} != solver {_val * MM} mm"
print("  dimension labels checked against the solver geometry: 5/5 agree")

# The radial axis is deliberately exaggerated so a 22 mm flow path and a 0.1 mm bore can share one
# panel.
fig.canvas.draw()
_bb = axA.get_window_extent()
_xr = axA.get_xlim()[1] - axA.get_xlim()[0]
_yr = abs(axA.get_ylim()[1] - axA.get_ylim()[0])
_exag = (_bb.width / _xr) / (_bb.height / _yr)
print(f"  radial exaggeration for the caption: {_exag:.2f}x")

axA.set_xlim(-7.20, 4.60)
axA.set_ylim(z3 * MM + 2.2, -4.6)
axA.set_axis_off()

def draw_mesh(ax, xlim, ylim):
    from matplotlib.collections import LineCollection
    keep = ((nodes[tri][:, :, 0]*MM <= xlim[1]+.05).all(1) &
            (nodes[tri][:, :, 1]*MM >= ylim[0]-.05).all(1) &
            (nodes[tri][:, :, 1]*MM <= ylim[1]+.05).all(1))
    segs = []
    for tt_ in tri[keep]:
        q = nodes[tt_]*MM
        segs += [[q[0], q[1]], [q[1], q[2]], [q[2], q[0]]]
    ax.add_collection(LineCollection(segs, colors=MESH, linewidths=MESH_LW, zorder=2))
    ax.add_patch(MplPolygon(np.column_stack([r, z]), closed=True,
                            facecolor="none", edgecolor=WALL, lw=1.2, zorder=3))

for ax, xlim, ylim, ttl in [
        (axB, (0, 1.30), (11.40, 12.70), "(b)  mesh at the contraction")]:
    draw_mesh(ax, xlim, ylim)
    ax.set_xlim(*xlim); ax.set_ylim(ylim[1], ylim[0])
    ax.set_aspect("equal", adjustable="box")
    if ttl is None:                       # the tip inset: frame it, keep it label-free
        ax.set_xticks([]); ax.set_yticks([])
        for sp in ax.spines.values():
            sp.set_visible(True); sp.set_linewidth(0.7); sp.set_color(S.MUTE)
        ax.set_facecolor("white")
    else:
        ax.grid(False)
        ax.set_xlabel(S.LBL["radius_mm"], labelpad=1.5)
        ax.set_ylabel(S.LBL["axial_z"], labelpad=1.5)
        ax.tick_params()
        for sp in ("top", "right"): ax.spines[sp].set_visible(False)

# No angle callout on panel (b).

# Panel titles on one baseline. axB is aspect-equal, so its axes box height is set by the data
# and its own set_title() floated far below panel (a)'s. Both are placed in figure coordinates.
fig.text(0.045, 0.945, "A", fontsize=S.PANEL_LABEL_PT,
         color=S.INK, ha="left", va="bottom", fontweight="bold")
fig.text(0.505, 0.945, "B", fontsize=S.PANEL_LABEL_PT,
         color=S.INK, ha="left", va="bottom", fontweight="bold")

# No legend text in the graphic.
print(f"  element count for the caption: {n_elem:,}")

# No two text labels may overlap.
import matplotlib.text as _mtext
fig.canvas.draw()
_rend = fig.canvas.get_renderer()
# Both panels, and panel (b)'s tick labels too: the tip-diameter callout in panel (a) sits
# beside panel (b)'s y tick labels, so a guard over one axes object would miss that pair.
_texts = [t for t in list(axA.texts) + list(axB.texts) if (t.get_text() or "").strip()]
_texts += [t for t in axB.get_yticklabels() + axB.get_xticklabels()
           if (t.get_text() or "").strip()]
_bad = []
for _i in range(len(_texts)):
    for _j in range(_i + 1, len(_texts)):
        # Measure the text only.
        _a = _mtext.Text.get_window_extent(_texts[_i], _rend)
        _b = _mtext.Text.get_window_extent(_texts[_j], _rend)
        # Overlap is a 2-D fact.
        _dx = min(_a.x1, _b.x1) - max(_a.x0, _b.x0)
        _dy = min(_a.y1, _b.y1) - max(_a.y0, _b.y0)
        if _dx > 3 and _dy > 3:
            _bad.append((_texts[_i].get_text().splitlines()[0],
                         _texts[_j].get_text().splitlines()[0], _dx * _dy))
if _bad:
    for _x, _y, _o in _bad:
        print(f"  OVERLAP {_x!r} x {_y!r}  ({_o:.0f} px^2)")
    raise SystemExit("panel (a) has overlapping labels; move one before saving")
print(f"  label overlap check: {len(_texts)} labels, none overlapping")

out = pathlib.Path(__file__).resolve().parents[1] / "results" / "figures" / "Fig2_geometry.png"
out.parent.mkdir(parents=True, exist_ok=True)
fig.savefig(out, dpi=P["dpi"], bbox_inches="tight", facecolor="white")
from l8_paths import flatten_png; flatten_png(out)
fig.savefig(out.with_suffix(".pdf"), bbox_inches="tight", facecolor="white")
print(f"saved: {out}  ({n_elem} elements)")
